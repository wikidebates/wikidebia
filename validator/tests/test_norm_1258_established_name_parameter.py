def test_1258_preexisting_legacy_nom_is_preserved_without_migration(tmp_path: Path):
    ctx = PackageContext(tmp_path, Report("0.4.62", str(tmp_path), ["wikicode"]), cache={"manifest.json": {"normative_versions": {"consolidated_norm": "1.2.58"}}})
    page = {
        "page_id": "A0001", "page_type": "argument", "language": "fr", "page_origin": "preexisting",
        "preserved_parameters": {
            "initialisation": {"present": False, "value": None},
            "nom": {"present": True, "value": "Argument cosmologique"},
            "avertissements-titre": {"present": False, "value": None},
            "avertissements-argument": {"present": False, "value": None},
            "avertissements-résumé": {"present": False, "value": None},
            "avertissements-références": {"present": False, "value": None},
            "avertissements-justifications": {"present": False, "value": None},
            "avertissements-objections": {"present": False, "value": None},
            "débat-détaillé": {"present": False, "value": None},
            "interlangue": {"present": False, "value": None},
            "date-création": {"present": True, "value": "2020-01-01"},
        },
    }
    tmpl = parse_template("""{{Argument
|nom=Argument cosmologique
|résumé=Résumé historique conservé exactement.
|rubriques=Philosophie
|mots-clés=Dieu
|date-création=2020-01-01
}}""")
    validate_template_shape(ctx, tmpl, "fr", "argument", "argument.wiki", page)
    assert not any(item.code == "WDV-MWK-023" for item in ctx.report.findings), ctx.report.to_text()
    assert not any(item.code == "WDV-MWK-003" and "nom" in item.message for item in ctx.report.findings), ctx.report.to_text()


