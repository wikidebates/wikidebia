from __future__ import annotations

import json
from pathlib import Path

from wikidebia_validator.package import PackageContext
from wikidebia_validator.report import Report
from wikidebia_validator.wikicode import (
    PROTECTED_PAGE_PARAMETERS,
    TOP,
    parse_template,
    validate_template_shape,
)


def _ctx(tmp_path: Path, language: str, name: str) -> PackageContext:
    review = tmp_path / "reviews/argument_name_discovery_review.json"
    review.parent.mkdir(parents=True, exist_ok=True)
    review.write_text(json.dumps({
        "entries": [{
            "language": language,
            "page_id": "A0001",
            "title": "Argument topic",
            "page_origin": "new",
            "search_reviewed": True,
            "search_queries": ["query one", "query two"],
            "search_scope_note": "Relevant academic terminology was checked.",
            "outcome": "known_name",
            "name": name,
            "evidence": [{"source": "Academic source", "label_as_used": name, "locator": "p. 1", "url": None}],
            "same_reasoning_confirmed": True,
            "non_invented_label_confirmed": True,
            "language_fit_confirmed": True,
            "rationale": "The same reasoning is explicitly designated by this established name.",
        }]
    }, ensure_ascii=False), encoding="utf-8")
    manifest = {
        "normative_versions": {"consolidated_norm": "1.2.58"},
        "editorial_controls": {"argument_name_discovery_path": "reviews/argument_name_discovery_review.json"},
    }
    (tmp_path / "manifest.json").write_text(json.dumps(manifest), encoding="utf-8")
    return PackageContext(tmp_path, Report("0.4.62", str(tmp_path), ["wikicode"]))


def test_1258_canonical_parameter_is_second_argument_slot_in_both_languages():
    assert TOP["fr", "argument"]["order"][:3] == ["initialisation", "nom-consacré", "nom"]
    assert TOP["en", "argument"]["order"][:3] == ["initialization", "established-name", "name"]
    assert PROTECTED_PAGE_PARAMETERS["fr", "argument"][:3] == ("initialisation", "nom-consacré", "nom")
    assert PROTECTED_PAGE_PARAMETERS["en", "argument"][:3] == ("initialization", "established-name", "name")


def test_1258_new_french_argument_accepts_nom_consacre(tmp_path: Path):
    ctx = _ctx(tmp_path, "fr", "Argument cosmologique")
    page = {"page_id": "A0001", "page_type": "argument", "language": "fr", "page_origin": "new", "preserved_parameters": {}}
    tmpl = parse_template("""{{Argument
|nom-consacré=Argument cosmologique
|avertissements-argument=Argument généré par IA
|résumé=Un résumé complet développe le raisonnement de cet argument.
|rubriques=Philosophie
|mots-clés=Dieu
|date-création=2026-08-10
}}""")
    validate_template_shape(ctx, tmpl, "fr", "argument", "argument.wiki", page)
    assert not any(item.code in {"WDV-MWK-003", "WDV-EDT-032"} for item in ctx.report.findings), ctx.report.to_text()


